#!/usr/bin/env python3
"""
This script reads a CSV file generated by DelayStatsVisualizer.
Each CSV row is expected to contain:
  timestamp,dumpId,refChannel,refBand,sigChannel,sigBand,delay,confidence,pslr

It groups data per channel assignment and plots delay versus timestamp.
Usage:
    python visualize_delay_stats.py stats.csv [--dump augmented.csv]
"""

import argparse
import csv
import os
import matplotlib.pyplot as plt

def read_csv_file(csv_file):
	"""
	Read the CSV file and return a list of dictionaries.
	Expected CSV columns:
	  timestamp,dumpId,refChannel,refBand,sigChannel,sigBand,delay,confidence,pslr
	"""
	data = []
	with open(csv_file, newline="") as f:
		reader = csv.reader(f)
		for row in reader:
			# Skip empty rows
			if not row:
				continue
			try:
				timestamp = float(row[0].strip())
				dump_id = int(row[1].strip())
				ref_channel = int(row[2].strip())
				ref_band = int(row[3].strip())
				sig_channel = int(row[4].strip())
				sig_band = int(row[5].strip())
				delay = float(row[6].strip())
				confidence = float(row[7].strip())
				pslr = float(row[8].strip())
				data.append({
					"timestamp": timestamp,
					"dump_id": dump_id,
					"ref_channel": ref_channel,
					"ref_band": ref_band,
					"sig_channel": sig_channel,
					"sig_band": sig_band,
					"delay": delay,
					"confidence": confidence,
					"pslr": pslr
				})
			except Exception as e:
				print("Error parsing row:", row, "\nException:", e)
	return data

def group_by_assignment(data):
	"""
	Group the data by channel assignment.
	The assignment key is in the form:
	    "ref_channel[ref_band] -> sig_channel[sig_band]"
	"""
	groups = {}
	for d in data:
		key = f'{d["ref_channel"]}[{d["ref_band"]}] -> {d["sig_channel"]}[{d["sig_band"]}]'
		if key not in groups:
			groups[key] = []
		groups[key].append(d)
	return groups

def plot_data(groups):
	"""
	Plot the delay data for each assignment group using the provided timestamp for the x-axis.
	"""
	plt.figure(figsize=(12, 8))
	for key, group in groups.items():
		# Sort the measurements by timestamp.
		sorted_group = sorted(group, key=lambda x: x["timestamp"])
		x = [d["timestamp"] for d in sorted_group]
		y = [d["delay"] for d in sorted_group]
		plt.plot(x, y, marker="o", linestyle="-", label=key)
	plt.xlabel("Timestamp (s)")
	plt.ylabel("Delay (ms)")
	plt.title("Delay Statistics Over Time")
	plt.legend()
	plt.grid(True)
	plt.tight_layout()
	plt.show()

def dump_with_timestamps(data, output_file):
	"""
	Dump an augmented CSV file with all data fields.
	"""
	fieldnames = [
		"timestamp", "dump_id", "ref_channel", "ref_band",
		"sig_channel", "sig_band", "delay", "confidence", "pslr"
	]
	with open(output_file, "w", newline="") as f:
		writer = csv.DictWriter(f, fieldnames=fieldnames)
		writer.writeheader()
		for d in data:
			writer.writerow(d)

def main():
	parser = argparse.ArgumentParser(description="Visualize delay CSV data over time.")
	parser.add_argument("csv_file", help="Input CSV file with delay statistics.")
	parser.add_argument("--dump", help="Dump augmented CSV with timestamp and other fields.")
	args = parser.parse_args()

	if not os.path.exists(args.csv_file):
		print(f"Error: File {args.csv_file} does not exist.")
		return

	# Read CSV data.
	data = read_csv_file(args.csv_file)
	if args.dump:
		dump_with_timestamps(data, args.dump)
		print(f"Augmented CSV data saved to {args.dump}")

	groups = group_by_assignment(data)
	plot_data(groups)

if __name__ == "__main__":
	main()
